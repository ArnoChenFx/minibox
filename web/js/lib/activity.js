/** An action without a label, such as one a newer server records, read as words: `notify.channel.test` → "Notify channel test". */
export function readableAction(action) {
  const words = String(action)
    .split(/[._-]+/)
    .filter(Boolean)
    .map((word) => (word.toLowerCase() === "ssh" ? "SSH" : word))
    .join(" ");
  return words ? words[0].toUpperCase() + words.slice(1) : String(action);
}
