/**
 * Embeds the built relay binaries into `src/preview/relay-binary.generated.ts` as base64, with
 * their sha256 hashes so the runtime can verify what it places in a box. Run after rebuilding the
 * relay (`cargo build --release --target <target>` in `relay/`, both musl targets). Release CI
 * runs this too, so the committed binary always matches the tagged source.
 *
 * Usage: bun scripts/build-relay.ts
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const targets = ["x86_64-unknown-linux-musl", "aarch64-unknown-linux-musl"] as const;

const lines: string[] = [
  "// Generated by scripts/build-relay.ts. Do not edit: rebuild the relay in `relay/` and rerun the",
  "// script. Each entry is one static musl build of `relay/src/main.rs`, base64 encoded, with its",
  "// sha256 so the runtime verifies a binary before it is placed in a box.",
  "",
  "export const RELAY_BINARIES: Readonly<Record<string, { readonly base64: string; readonly sha256: string }>> = {",
];

for (const target of targets) {
  const path = join(root, "relay", "target", target, "release", "minibox-relay");
  const bytes = readFileSync(path);
  if (bytes.length < 100_000) throw new Error(`${path} looks truncated (${bytes.length} bytes)`);
  const sha256 = createHash("sha256").update(bytes).digest("hex");
  const chunks = bytes.toString("base64").match(/.{1,100}/g) ?? [];
  const body = chunks.map((chunk) => `      "${chunk}"`).join(" +\n");
  lines.push(`  "${target}": {`);
  lines.push(`    sha256: "${sha256}",`);
  lines.push("    base64:");
  lines.push(body + ",");
  lines.push("  },");
}
lines.push("};", "");
const out = join(root, "src", "preview", "relay-binary.generated.ts");
mkdirSync(join(root, "src", "preview"), { recursive: true });
writeFileSync(out, lines.join("\n"));
console.log(`wrote ${out} (${targets.length} targets)`);
